    public function index()
    {
        $categories = Category::latest();
        $keyword = request('keyword');

        if ($keyword) {
            $categories->where('name', 'like', '%' . $keyword . '%');
        }

        return view('categories.index', [
            'title' => 'Category',
            'categories' => $categories->paginate(5)->withQueryString(),
        ]);
    }

